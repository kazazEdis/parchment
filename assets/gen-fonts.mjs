// Generates src/fonts.ts: the metric-compatible web fonts embedded as base64 @font-face, so the
// renderer measures + paints with Calibri-equivalent metrics (Carlito) on any machine. Run from repo
// root: node assets/gen-fonts.mjs
import fs from "fs";

// unicode-range per fontsource (latin basic incl. € U+20AC; latin-ext incl. Croatian č ć ž š đ).
const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
const LATIN_EXT = "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF";

const b64 = (p) => fs.readFileSync(p).toString("base64");
const face = (weight, range, file) =>
  `@font-face{font-family:'Carlito';font-style:normal;font-weight:${weight};font-display:swap;` +
  `src:url(data:font/woff2;base64,${b64("assets/fonts/" + file)}) format('woff2');unicode-range:${range}}`;

const css = [
  face(400, LATIN, "carlito-latin-400-normal.woff2"),
  face(400, LATIN_EXT, "carlito-latin-ext-400-normal.woff2"),
  face(700, LATIN, "carlito-latin-700-normal.woff2"),
  face(700, LATIN_EXT, "carlito-latin-ext-700-normal.woff2"),
].join("");

const out = `// AUTO-GENERATED by assets/gen-fonts.mjs — do not edit by hand.
// Metric-compatible web fonts embedded as base64 @font-face so the renderer measures line breaks and
// paginates with the SAME glyph advances as Word (Calibri ≈ Carlito), independent of installed fonts.
// Inject once into any document that renders a .docx (preview, the print popup, the editor).

export const FONT_FACE_CSS = ${JSON.stringify(css)};

const MARK = "data-parchment-fonts";

/** Inject FONT_FACE_CSS into a document's <head> exactly once (idempotent). Returns when injected. */
export function ensureFontsInjected(doc: Document = document): void {
  try {
    if (doc.querySelector(\`style[\${MARK}]\`)) return;
    const style = doc.createElement("style");
    style.setAttribute(MARK, "1");
    style.textContent = FONT_FACE_CSS;
    doc.head.appendChild(style);
  } catch { /* no-op outside a DOM */ }
}
`;
fs.writeFileSync("src/fonts.ts", out);
console.log("src/fonts.ts written,", (out.length / 1024).toFixed(0), "KB");
